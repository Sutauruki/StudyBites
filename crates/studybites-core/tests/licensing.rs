//! Phase 3: device binding, activation codes, key derivation and the
//! encrypted-at-rest guarantees (Brief Sections 8 and 9).
//!
//! The acceptance criteria are stated as properties here: an activated install
//! works, a copy on another device does not, and a forged or altered code is
//! refused.

use ed25519_dalek::{Signer, SigningKey};
use studybites_core::db::Key;
use studybites_core::device::{self, Component, DeviceProfile};
use studybites_core::license::{self, License, SECRET_LEN};
use studybites_core::{base32, crypto, Db};

/// A throwaway issuing key. The real private key never exists in this
/// repository — it is generated by `license-tool` on the owner's machine.
fn issuer() -> SigningKey {
    SigningKey::from_bytes(&[42u8; 32])
}

fn profile_for(guid: &str) -> DeviceProfile {
    DeviceProfile {
        machine_guid: Some(guid.to_string()),
        components: vec![
            Component {
                name: "machine_guid".into(),
                hash: format!("hash-of-{guid}"),
            },
            Component {
                name: "cpu".into(),
                hash: "hash-of-cpu".into(),
            },
        ],
    }
}

/// Stand in for the owner running `license-tool issue`.
fn issue_for(profile: &DeviceProfile, buyer: &str) -> String {
    let license = License {
        license_id: 7,
        device_tag: profile.device_tag().unwrap(),
        issued_days: 20_400,
        features: 0,
        secret: [9u8; SECRET_LEN],
        buyer_name: buyer.to_string(),
    };
    let body = license.signing_body().unwrap();
    let signature = issuer().sign(&body);
    license.encode(&signature.to_bytes()).unwrap()
}

// ---- base32 -------------------------------------------------------------

#[test]
fn codes_survive_the_ways_people_mistype_them() {
    let bytes: Vec<u8> = (0u8..40).collect();
    let code = base32::encode_grouped(&bytes);

    assert_eq!(base32::decode(&code).unwrap()[..40], bytes[..]);

    // Lower case, spaces instead of dashes, and the Crockford substitutions
    // all have to land on the same bytes.
    let mangled = code.to_lowercase().replace('-', " ");
    assert_eq!(base32::decode(&mangled).unwrap()[..40], bytes[..]);

    let substituted = code.replace('1', "I").replace('0', "O");
    assert_eq!(base32::decode(&substituted).unwrap()[..40], bytes[..]);

    // A dropped character must not silently decode to something plausible.
    let truncated: String = code.chars().filter(|c| *c != '-').take(10).collect();
    assert_ne!(
        base32::decode(&truncated).unwrap_or_default()[..],
        bytes[..]
    );
}

// ---- request code -------------------------------------------------------

#[test]
fn a_request_code_round_trips_and_catches_a_typo() {
    let profile = profile_for("device-one");
    let request = license::RequestCode {
        device_tag: profile.device_tag().unwrap(),
        app_major: 0,
        app_minor: 1,
    };

    let code = request.encode();
    assert_eq!(license::RequestCode::decode(&code).unwrap(), request);

    // Short enough to read down a phone line: 13 bytes of payload.
    assert!(
        code.chars().filter(|c| *c != '-').count() <= 24,
        "request code got long: {code}"
    );

    // Change one character; the checksum must notice.
    let chars: Vec<char> = code.chars().filter(|c| *c != '-').collect();
    let mut broken = chars.clone();
    broken[3] = if broken[3] == 'A' { 'B' } else { 'A' };
    let broken: String = broken.into_iter().collect();
    if broken != chars.into_iter().collect::<String>() {
        assert!(license::RequestCode::decode(&broken).is_err());
    }
}

// ---- activation ---------------------------------------------------------

#[test]
fn an_activation_code_verifies_and_names_its_buyer() {
    let profile = profile_for("device-one");
    let code = issue_for(&profile, "Odejayi Ezekiel");

    let verified = license::verify(&code, &issuer().verifying_key().to_bytes()).unwrap();
    assert!(verified.matches_device(&profile.device_tag().unwrap()));

    let license = verified.license();
    assert_eq!(license.buyer_name, "Odejayi Ezekiel");
    assert_eq!(license.license_id, 7);
    assert_eq!(license.secret, [9u8; SECRET_LEN]);
}

#[test]
fn a_valid_code_for_another_device_is_refused() {
    let theirs = profile_for("device-one");
    let mine = profile_for("device-two");
    let code = issue_for(&theirs, "Someone Else");

    // The signature is genuine — this is the copied-app-folder case.
    let verified = license::verify(&code, &issuer().verifying_key().to_bytes()).unwrap();
    assert!(
        !verified.matches_device(&mine.device_tag().unwrap()),
        "a licence must not travel to another machine"
    );
}

#[test]
fn a_forged_or_altered_code_is_rejected() {
    let profile = profile_for("device-one");
    let code = issue_for(&profile, "Odejayi Ezekiel");
    let public = issuer().verifying_key().to_bytes();

    // Signed by somebody else's key entirely.
    let forger = SigningKey::from_bytes(&[1u8; 32]);
    let license = License {
        license_id: 7,
        device_tag: profile.device_tag().unwrap(),
        issued_days: 20_400,
        features: 0,
        secret: [9u8; SECRET_LEN],
        buyer_name: "Pirate".into(),
    };
    let body = license.signing_body().unwrap();
    let forged = license.encode(&forger.sign(&body).to_bytes()).unwrap();
    assert!(license::verify(&forged, &public).is_err());

    // A genuine code with one byte of the payload flipped.
    let mut bytes = base32::decode(&code).unwrap();
    bytes[5] ^= 0xff;
    assert!(license::verify(&base32::encode_grouped(&bytes), &public).is_err());

    // Nonsense in the box.
    assert!(license::verify("not-a-code", &public).is_err());
    assert!(license::verify("", &public).is_err());
}

// ---- key derivation -----------------------------------------------------

#[test]
fn keys_are_deterministic_per_device_and_differ_across_them() {
    let one = profile_for("device-one").device_id().unwrap();
    let two = profile_for("device-two").device_id().unwrap();
    let secret = [9u8; SECRET_LEN];

    let a = crypto::derive(&one, &secret);
    let b = crypto::derive(&one, &secret);
    assert_eq!(
        a.db.as_bytes(),
        b.db.as_bytes(),
        "the same machine must derive the same key every launch"
    );

    let other = crypto::derive(&two, &secret);
    assert_ne!(a.db.as_bytes(), other.db.as_bytes());

    // A different licence on the same machine is a different key too.
    let relicensed = crypto::derive(&one, &[8u8; SECRET_LEN]);
    assert_ne!(a.db.as_bytes(), relicensed.db.as_bytes());

    // The two derived keys must not be the same key under two names.
    assert_ne!(a.db.as_bytes(), a.file.as_bytes());
}

#[test]
fn a_database_copied_to_another_device_will_not_open() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("studybites.db");
    let secret = [9u8; SECRET_LEN];

    let mine = crypto::derive(&profile_for("device-one").device_id().unwrap(), &secret);
    {
        let db = Db::open(&path, Key::Raw(&mine.db)).unwrap();
        studybites_core::subjects::create(&db, "CIT 202").unwrap();
    }

    // Same file, same activation code, different machine.
    let theirs = crypto::derive(&profile_for("device-two").device_id().unwrap(), &secret);
    assert!(
        Db::open(&path, Key::Raw(&theirs.db)).is_err(),
        "copying the data folder to another PC must get them nothing"
    );

    // And it still opens for its owner.
    let db = Db::open(&path, Key::Raw(&mine.db)).unwrap();
    assert_eq!(
        studybites_core::subjects::list(&db, false).unwrap().len(),
        1
    );
}

#[test]
fn an_existing_development_database_is_rekeyed_rather_than_lost() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("studybites.db");

    // What an install made before licensing existed looks like.
    {
        let db = Db::open(&path, studybites_core::db::DEV_KEY).unwrap();
        studybites_core::subjects::create(&db, "MTH 101").unwrap();
    }

    let keys = crypto::derive(
        &profile_for("device-one").device_id().unwrap(),
        &[9u8; SECRET_LEN],
    );
    let db = Db::open_or_rekey(&path, Key::Raw(&keys.db)).unwrap();
    assert_eq!(
        studybites_core::subjects::list(&db, false).unwrap().len(),
        1,
        "activating must not throw away work already done"
    );
    drop(db);

    // Afterwards it is the derived key that opens it, and the old one does not.
    assert!(Db::open(&path, Key::Raw(&keys.db)).is_ok());
    assert!(Db::open(&path, studybites_core::db::DEV_KEY).is_err());
}

// ---- drift --------------------------------------------------------------

#[test]
fn a_changed_component_is_reported_but_never_locks_anyone_out() {
    let activated = profile_for("device-one").components;
    let mut now = activated.clone();
    now[1].hash = "hash-of-a-new-cpu".into();

    let drift = device::drift(&activated, &now);
    assert!(!drift.is_same_machine());
    assert_eq!(drift.changed, vec!["cpu".to_string()]);
    assert_eq!(drift.matched, 1);

    // The device id is unchanged, so the licence and the keys still work.
    // That is the point: swapping a CPU must not cost you your notes.
    assert_eq!(
        profile_for("device-one").device_id().unwrap(),
        profile_for("device-one").device_id().unwrap()
    );

    // A component we could not read this time is not evidence of anything.
    let partial = vec![activated[0].clone()];
    assert!(device::drift(&activated, &partial).is_same_machine());
}

// ---- EULA ---------------------------------------------------------------

#[test]
fn eula_acceptance_is_recorded_per_version() {
    let db = Db::open_in_memory(studybites_core::db::DEV_KEY).unwrap();
    assert!(!license::eula_accepted(&db, "1.0").unwrap());

    license::record_eula(&db, "1.0", "2026-10-27T09:00:00Z").unwrap();
    assert!(license::eula_accepted(&db, "1.0").unwrap());

    // A revised agreement has to be accepted again.
    assert!(!license::eula_accepted(&db, "1.1").unwrap());
}

#[test]
fn the_public_key_is_compiled_in_from_the_environment() {
    // Compile-time, so this asserts whichever way the build was made. CI
    // builds the installer with the secret set; this repository never holds
    // either half of the key pair.
    match option_env!("STUDYBITES_LICENSE_PUBKEY") {
        Some(hex) if hex.trim().len() == 64 => {
            assert!(license::embedded_public_key().is_some());
            assert!(license::licensing_enabled());
        }
        _ => {
            assert!(
                license::embedded_public_key().is_none(),
                "a build with no key must not claim to have one"
            );
            assert!(!license::licensing_enabled());
        }
    }
}
